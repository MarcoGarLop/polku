import { createServer, type IncomingMessage, type ServerResponse } from 'node:http';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runAgent, type AgentResponse, type ChatMessage, type UiContext } from './agent';
import { cacheState, FALLBACK_MODEL, MODEL, warmUp } from './gemini';
import { buildPlan } from './plan';
import { designAction, type DesignResult } from './design';
import { compareNordic, PRACTICES, type NordicResult } from './nordic';

const PORT = Number(process.env.PORT || 8787);
const DEMO_MODE = process.env.DEMO_MODE === 'true';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const DEMO_FILE = join(ROOT, 'demo', 'cached-responses.json');
const AGENT_TIMEOUT_MS = 70000;

/* ---------- demo cache: every good live answer is recorded; in DEMO_MODE it is replayed instantly ---------- */
type DemoCache = Record<string, AgentResponse>;
const loadDemo = (): DemoCache => {
  try {
    return JSON.parse(readFileSync(DEMO_FILE, 'utf8')).entries ?? {};
  } catch {
    return {};
  }
};
let demo = loadDemo();
const key = (q: string, ui: UiContext) => `${q.toLowerCase().replace(/[^a-z0-9äöå ]/g, '').replace(/\s+/g, ' ').trim()}|${ui.regionId ?? ''}`;
function saveDemo(k: string, r: AgentResponse) {
  demo[k] = r;
  if (!existsSync(dirname(DEMO_FILE))) mkdirSync(dirname(DEMO_FILE), { recursive: true });
  writeFileSync(DEMO_FILE, JSON.stringify({ _readme: 'Recorded Gemini answers for the offline demo. Generated by apps/server.', entries: demo }, null, 2));
}

/* ---------- designed actions: also recorded for the offline demo ---------- */
const DESIGN_FILE = join(ROOT, 'demo', 'designed-actions.json');
const designs: Record<string, DesignResult> = (() => {
  try {
    return JSON.parse(readFileSync(DESIGN_FILE, 'utf8')).entries ?? {};
  } catch {
    return {};
  }
})();
function saveDesign(k: string, r: DesignResult) {
  designs[k] = r;
  writeFileSync(DESIGN_FILE, JSON.stringify({ _readme: 'Actions designed with Gemini, recorded for the offline demo.', entries: designs }, null, 2));
}

/* ---------- Nordic practices: recorded too ---------- */
const NORDIC_FILE = join(ROOT, 'demo', 'nordic-practices.json');
const nordic: Record<string, NordicResult> = (() => {
  try {
    return JSON.parse(readFileSync(NORDIC_FILE, 'utf8')).entries ?? {};
  } catch {
    return {};
  }
})();

async function readBody(req: IncomingMessage): Promise<any> {
  const chunks: Buffer[] = [];
  for await (const c of req) chunks.push(c as Buffer);
  const raw = Buffer.concat(chunks).toString('utf8');
  return raw ? JSON.parse(raw) : {};
}
function send(res: ServerResponse, status: number, body: unknown) {
  res.writeHead(status, { 'content-type': 'application/json; charset=utf-8' });
  res.end(JSON.stringify(body));
}
const withTimeout = <T,>(p: Promise<T>, ms: number) => Promise.race([p, new Promise<T>((_, rej) => setTimeout(() => rej(new Error(`timeout after ${ms} ms`)), ms))]);

const server = createServer(async (req, res) => {
  const url = new URL(req.url ?? '/', 'http://localhost');
  try {
    if (req.method === 'GET' && url.pathname === '/api/health') {
      return send(res, 200, { ok: true, model: MODEL, fallbackModel: FALLBACK_MODEL, demoMode: DEMO_MODE, context: cacheState, recordedAnswers: Object.keys(demo).length });
    }

    if (req.method === 'POST' && url.pathname === '/api/agent') {
      const body = await readBody(req);
      const messages: ChatMessage[] = (body.messages ?? []).filter((m: any) => m && typeof m.text === 'string').slice(-8);
      const ui: UiContext = body.ui ?? {};
      const last = messages[messages.length - 1];
      if (!last || last.role !== 'user') return send(res, 400, { error: 'last message must be from the user' });
      const k = key(last.text, ui);
      const fresh = url.searchParams.get('fresh') === '1';
      if (DEMO_MODE && !fresh && demo[k] && messages.length === 1) return send(res, 200, { ...demo[k], mode: 'demo-cache', ms: 0 });
      try {
        // Chat defaults to the fast model (~3× quicker for a multi-tool answer); ?speed=deep uses the flagship model.
        const deep = (url.searchParams.get('speed') ?? process.env.AGENT_SPEED ?? 'fast') === 'deep';
        let out: AgentResponse;
        try {
          out = await withTimeout(runAgent(messages, ui, { useFallback: !deep }), AGENT_TIMEOUT_MS);
        } catch (e: any) {
          console.warn(`! agent failed (${String(e?.message).slice(0, 160)}), retrying with the other model`);
          out = await withTimeout(runAgent(messages, ui, { useFallback: deep }), AGENT_TIMEOUT_MS);
        }
        if (out.text && messages.length === 1) saveDemo(k, out);
        console.log(`→ agent ${out.model}/${out.mode} ${out.ms} ms · ${out.toolCalls.length} tools · unverified ${out.verification.unverified.length}`);
        return send(res, 200, out);
      } catch (e: any) {
        if (demo[k]) return send(res, 200, { ...demo[k], mode: 'demo-cache', ms: 0 });
        return send(res, 503, { error: String(e?.message ?? e).slice(0, 300) });
      }
    }

    if (req.method === 'POST' && url.pathname === '/api/design-action') {
      const b = await readBody(req);
      const idea = String(b.idea ?? '').trim().slice(0, 300);
      if (idea.length < 6) return send(res, 400, { error: 'describe the action in a few words' });
      const k = `${idea.toLowerCase().replace(/[^a-z0-9äöå ]/g, '').replace(/\s+/g, ' ')}|${b.regionId ?? ''}`;
      if (DEMO_MODE && url.searchParams.get('fresh') !== '1' && designs[k]) return send(res, 200, { ...designs[k], cached: true });
      try {
        const out = await withTimeout(designAction(idea, b.regionId ?? 'lappi', b.profileA, b.profileB), 90000);
        saveDesign(k, out);
        console.log(`→ design "${idea.slice(0, 50)}" ${out.model} ${out.ms} ms · ${out.estimate.effects.length} effects`);
        return send(res, 200, out);
      } catch (e: any) {
        if (designs[k]) return send(res, 200, { ...designs[k], cached: true });
        return send(res, 503, { error: String(e?.message ?? e).slice(0, 300) });
      }
    }

    if (req.method === 'GET' && url.pathname === '/api/nordic') {
      return send(res, 200, PRACTICES);
    }

    if (req.method === 'POST' && url.pathname === '/api/nordic') {
      const b = await readBody(req);
      const id = String(b.practiceId ?? '');
      if (DEMO_MODE && url.searchParams.get('fresh') !== '1' && nordic[id]) return send(res, 200, { ...nordic[id], cached: true });
      try {
        const out = await withTimeout(compareNordic(id), 100000);
        nordic[id] = out;
        writeFileSync(NORDIC_FILE, JSON.stringify({ _readme: 'Nordic practices compared by Gemini, recorded for the offline demo.', entries: nordic }, null, 2));
        console.log(`→ nordic ${id} ${out.model} ${out.ms} ms · unverified ${out.unverified.length}`);
        return send(res, 200, out);
      } catch (e: any) {
        if (nordic[id]) return send(res, 200, { ...nordic[id], cached: true });
        return send(res, 503, { error: String(e?.message ?? e).slice(0, 300) });
      }
    }

    if (req.method === 'POST' && url.pathname === '/api/plan') {
      const b = await readBody(req);
      const plan = await withTimeout(buildPlan(b.regionId ?? 'lappi', b.priority ?? 'equity', b.budget ?? 'medium', b.lang === 'fi' ? 'fi' : 'en'), 60000);
      return send(res, 200, plan);
    }

    send(res, 404, { error: 'not found' });
  } catch (e: any) {
    console.error(e);
    send(res, 500, { error: String(e?.message ?? e).slice(0, 300) });
  }
});

server.listen(PORT, () => {
  console.log(`Polku server on http://localhost:${PORT} · model ${MODEL} (fallback ${FALLBACK_MODEL}) · demo mode ${DEMO_MODE}`);
  warmUp();
});
