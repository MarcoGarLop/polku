// Gemini estimates the effect of every Polku action from the evidence (run once; result is stored and reviewed).
// Run: node --env-file=../../.env --import tsx src/estimate-all.ts
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Type } from '@google/genai';
import { ESTIMATION_RULES, estimateSchema, geminiJson, sanitize, type AiEstimate } from './estimate';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

// Descriptions only: Gemini does NOT see the team's own effect sizes, so its estimate is independent.
const ACTIONS = [
  { id: 'fast_track', what: 'Standardised Nordic-style fast-track diagnostic pathway with standard referral criteria (like Denmark CPP, Sweden SVF, Norway pakkeforløp), from referral to treatment start.' },
  { id: 'econsult', what: 'Electronic consultation between the GP and the lung specialist, so the GP gets advice before or instead of a formal referral.' },
  { id: 'navigator', what: 'A named nurse navigator / care coordinator for every suspected lung cancer, especially for patients who live alone or find the system hard to navigate.' },
  { id: 'direct_ct', what: 'Direct access to CT scans for GPs in primary care, without a specialist referral.' },
  { id: 'gp_continuity', what: 'A named family doctor (omalääkäri) for continuity of care in primary care.' },
  { id: 'awareness', what: 'A multilingual symptom-awareness and anti-stigma campaign for lung cancer, aimed at people with lower health literacy.' },
  { id: 'remote_care', what: 'Remote oncology consultations plus travel coordination for patients far from the hospital.' },
  { id: 'public_fast_lane', what: 'A fast lane for suspected cancer from the PUBLIC health centre: standard criteria send suspected cases straight to the fast-track pathway, so public patients stop being slower than occupational/private ones.' },
  { id: 'travel_cost_support', what: 'Organised and reimbursed travel (Kela) for patients far from hospital or with low income.' },
];

const prompt = `Estimate the effect on Polku's five pathway phases of each of these actions, for Finland's lung cancer pathway.
${ESTIMATION_RULES}

Actions:
${ACTIONS.map((a) => `- id "${a.id}": ${a.what}`).join('\n')}

Return one estimate per action, keeping the ids.`;

const { data, model, ms } = await geminiJson<{ estimates: AiEstimate[] }>(prompt, { type: Type.OBJECT, properties: { estimates: { type: Type.ARRAY, items: estimateSchema } }, required: ['estimates'] });
const estimates = (data.estimates ?? []).map(sanitize).filter((e) => ACTIONS.some((a) => a.id === e.id));
const out = {
  _readme: 'Effect sizes ESTIMATED BY GEMINI from the evidence digest (docs/05) and the full strategy + roadmap. Generated by apps/server/src/estimate-all.ts. The simulator uses these instead of the team priors in pathway_parameters.json (kept there as "team prior" for comparison).',
  model,
  generated: new Date().toISOString(),
  seconds: Math.round(ms / 1000),
  estimates,
};
writeFileSync(join(ROOT, 'data', 'seed', 'ai_effects.json'), JSON.stringify(out, null, 2));
console.log(`✓ ${estimates.length} estimates by ${model} in ${Math.round(ms / 1000)} s`);
for (const e of estimates)
  console.log(`- ${e.id} [${e.confidence}] ${e.effects.map((f) => `${f.phase}${f.kind === 'share_of_distance_days' ? '(dist)' : ''}${f.appliesTo !== 'all' ? '/' + f.appliesTo : ''} −${Math.round(f.mid * 100)}% (${Math.round(f.low * 100)}–${Math.round(f.high * 100)})`).join(', ')} · ${e.evidence.join(', ')}`);
